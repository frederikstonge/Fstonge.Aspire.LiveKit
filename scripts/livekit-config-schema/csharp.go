package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type schemaDocument map[string]any

type csharpGenerator struct {
	definitions map[string]schemaDocument
	typeNames   map[string]string
	rootType    string
	rootSchema  schemaDocument
}

func generateCSharp(schema schemaDocument, namespace, rootType string) ([]byte, error) {
	rawDefinitions, ok := schema["$defs"].(map[string]any)
	if !ok && schema["$defs"] != nil {
		return nil, fmt.Errorf("schema $defs value is not an object")
	}
	if !ok {
		rawDefinitions = map[string]any{}
	}

	g := &csharpGenerator{
		definitions: make(map[string]schemaDocument, len(rawDefinitions)),
		typeNames:   make(map[string]string, len(rawDefinitions)),
		rootType:    csharpIdentifier(rootType),
		rootSchema:  schema,
	}
	for key, rawDefinition := range rawDefinitions {
		definition, ok := rawDefinition.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("definition %q is not an object", key)
		}
		g.definitions[key] = schemaDocument(definition)
	}
	g.assignTypeNames()

	var source bytes.Buffer
	source.WriteString("// <auto-generated />\n")
	source.WriteString("#nullable enable\n\n")
	source.WriteString("using System.Collections.Generic;\n")
	source.WriteString("using YamlDotNet.Serialization;\n\n")
	fmt.Fprintf(&source, "namespace %s;\n\n", namespace)

	fmt.Fprintf(&source, "public sealed class %s\n{\n", g.rootType)
	if err := g.writeProperties(&source, schema, "    ", true); err != nil {
		return nil, err
	}
	source.WriteString("}\n")

	keys := make([]string, 0, len(g.definitions))
	for key := range g.definitions {
		if g.isObjectDefinition(g.definitions[key]) {
			keys = append(keys, key)
		}
	}
	sort.Strings(keys)
	for _, key := range keys {
		definition := g.definitions[key]
		source.WriteString("\n")
		fmt.Fprintf(&source, "public sealed class %s\n{\n", g.typeNames[key])
		if err := g.writeProperties(&source, definition, "    ", false); err != nil {
			return nil, fmt.Errorf("definition %q: %w", key, err)
		}
		source.WriteString("}\n")
	}

	return source.Bytes(), nil
}

func (g *csharpGenerator) assignTypeNames() {
	baseNames := make(map[string][]string)
	propertyNames := make(map[string]map[string]struct{})
	for key := range g.definitions {
		if !g.isObjectDefinition(g.definitions[key]) {
			continue
		}
		baseName := csharpIdentifier(strings.SplitN(key, "_", 2)[0])
		baseNames[baseName] = append(baseNames[baseName], key)
	}
	g.collectReferencePropertyNames(propertyNames)

	candidates := make(map[string]string)
	candidateCounts := make(map[string]int)
	for key := range g.definitions {
		if !g.isObjectDefinition(g.definitions[key]) {
			continue
		}
		baseName := csharpIdentifier(strings.SplitN(key, "_", 2)[0])
		if baseName != "Config" || len(propertyNames[key]) != 1 {
			continue
		}
		for propertyName := range propertyNames[key] {
			candidate := propertyName + "Config"
			if candidate == g.rootType {
				continue
			}
			candidates[key] = candidate
			candidateCounts[candidate]++
		}
	}
	for candidate := range candidateCounts {
		if _, exists := baseNames[candidate]; exists {
			candidateCounts[candidate]++
		}
	}

	for baseName, keys := range baseNames {
		sort.Strings(keys)
		for _, key := range keys {
			name := baseName
			if candidate, exists := candidates[key]; exists && candidateCounts[candidate] == 1 {
				name = candidate
			} else if len(keys) > 1 {
				hash := strings.SplitN(key, "_", 2)
				if len(hash) == 2 {
					name += "_" + hash[1]
				}
			}
			g.typeNames[key] = name
		}
	}
}

func (g *csharpGenerator) collectReferencePropertyNames(propertyNames map[string]map[string]struct{}) {
	var visit func(any, string)
	visit = func(value any, propertyName string) {
		switch value := value.(type) {
		case map[string]any:
			if reference, ok := value["$ref"].(string); ok {
				const prefix = "#/$defs/"
				if strings.HasPrefix(reference, prefix) {
					key := strings.TrimPrefix(reference, prefix)
					if propertyNames[key] == nil {
						propertyNames[key] = make(map[string]struct{})
					}
					propertyNames[key][csharpIdentifier(propertyName)] = struct{}{}
				}
			}
			for key, child := range value {
				if key == "properties" {
					if properties, ok := child.(map[string]any); ok {
						for name, property := range properties {
							visit(property, name)
						}
					}
					continue
				}
				visit(child, propertyName)
			}
		case []any:
			for _, child := range value {
				visit(child, propertyName)
			}
		}
	}

	definitions := make(map[string]any, len(g.definitions))
	for key, definition := range g.definitions {
		definitions[key] = map[string]any(definition)
	}
	visit(definitions, "")
	visit(map[string]any(g.rootSchema), "")
}

func (g *csharpGenerator) isObjectDefinition(schema schemaDocument) bool {
	if schema["type"] != "object" {
		return false
	}
	_, hasProperties := schema["properties"].(map[string]any)
	return hasProperties
}

func (g *csharpGenerator) writeProperties(source *bytes.Buffer, schema schemaDocument, indent string, initializeObjectReferences bool) error {
	properties, ok := schema["properties"].(map[string]any)
	if !ok {
		return nil
	}
	keys := make([]string, 0, len(properties))
	for key := range properties {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	usedNames := make(map[string]int, len(keys))
	for _, key := range keys {
		rawProperty := properties[key]
		propertySchema, ok := rawProperty.(map[string]any)
		if !ok {
			return fmt.Errorf("property %q is not a schema object", key)
		}
		propertyName := csharpIdentifier(key)
		usedNames[propertyName]++
		if usedNames[propertyName] > 1 {
			propertyName += strconv.Itoa(usedNames[propertyName])
		}

		propertyType, err := g.typeFor(propertySchema)
		if err != nil {
			return fmt.Errorf("property %q: %w", key, err)
		}
		fmt.Fprintf(source, "%s[YamlMember(Alias = %s)]\n", indent, strconv.Quote(key))
		initialize := initializeObjectReferences && g.isObjectReference(propertySchema)
		if initialize {
			propertyType = strings.TrimSuffix(propertyType, "?")
		}
		fmt.Fprintf(source, "%spublic %s %s { get; set; }", indent, propertyType, propertyName)
		if initialize {
			fmt.Fprint(source, " = new();")
		}
		fmt.Fprint(source, "\n\n")
	}
	return nil
}

func (g *csharpGenerator) isObjectReference(schema map[string]any) bool {
	if reference, ok := schema["$ref"].(string); ok {
		const prefix = "#/$defs/"
		if !strings.HasPrefix(reference, prefix) {
			return false
		}
		return g.isObjectDefinition(g.definitions[strings.TrimPrefix(reference, prefix)])
	}
	if alternatives, ok := schema["anyOf"].([]any); ok {
		for _, alternative := range alternatives {
			candidate, ok := alternative.(map[string]any)
			if ok && candidate["type"] != "null" && g.isObjectReference(candidate) {
				return true
			}
		}
	}
	return false
}

func (g *csharpGenerator) typeFor(schema map[string]any) (string, error) {
	if reference, ok := schema["$ref"].(string); ok {
		const prefix = "#/$defs/"
		if !strings.HasPrefix(reference, prefix) {
			return "", fmt.Errorf("unsupported reference %q", reference)
		}
		key := strings.TrimPrefix(reference, prefix)
		definition, exists := g.definitions[key]
		if !exists {
			return "", fmt.Errorf("reference %q was not found", reference)
		}
		if typeName, exists := g.typeNames[key]; exists {
			return typeName + "?", nil
		}
		return g.typeFor(map[string]any(definition))
	}

	if alternatives, ok := schema["anyOf"].([]any); ok {
		nonNull := make([]map[string]any, 0, len(alternatives))
		nullable := false
		for _, alternative := range alternatives {
			candidate, ok := alternative.(map[string]any)
			if !ok {
				return "", fmt.Errorf("anyOf alternative is not a schema object")
			}
			if candidate["type"] == "null" {
				nullable = true
				continue
			}
			nonNull = append(nonNull, candidate)
		}
		if len(nonNull) == 1 {
			valueType, err := g.typeFor(nonNull[0])
			if err != nil {
				return "", err
			}
			if nullable {
				return makeNullable(valueType), nil
			}
			return valueType, nil
		}
		return "object?", nil
	}

	if itemSchema, ok := schema["items"].(map[string]any); ok {
		itemType, err := g.typeFor(itemSchema)
		if err != nil {
			return "", err
		}
		return "List<" + itemType + ">?", nil
	}
	if additional, ok := schema["additionalProperties"].(map[string]any); ok {
		valueType, err := g.typeFor(additional)
		if err != nil {
			return "", err
		}
		return "Dictionary<string, " + valueType + ">?", nil
	}

	switch schema["type"] {
	case "object":
		return "object?", nil
	case "array":
		return "List<object?>?", nil
	case "string":
		return "string?", nil
	case "boolean":
		return "bool?", nil
	case "integer":
		return "long?", nil
	case "number":
		return "double?", nil
	case "null":
		return "object?", nil
	case nil:
		return "object?", nil
	default:
		return "", fmt.Errorf("unsupported JSON Schema type %v", schema["type"])
	}
}

func makeNullable(typeName string) string {
	if strings.HasSuffix(typeName, "?") {
		return typeName
	}
	return typeName + "?"
}

func csharpIdentifier(value string) string {
	var result strings.Builder
	upperNext := true
	for _, character := range value {
		if !unicode.IsLetter(character) && !unicode.IsDigit(character) {
			upperNext = true
			continue
		}
		if result.Len() == 0 && !unicode.IsLetter(character) {
			result.WriteByte('_')
		}
		if upperNext {
			result.WriteRune(unicode.ToUpper(character))
			upperNext = false
		} else {
			result.WriteRune(character)
		}
	}
	identifier := result.String()
	if identifier == "" {
		return "_"
	}
	if isCSharpKeyword(identifier) {
		return "@" + identifier
	}
	return identifier
}

func isCSharpKeyword(identifier string) bool {
	switch identifier {
	case "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char",
		"checked", "class", "const", "continue", "decimal", "default", "delegate", "do",
		"double", "else", "enum", "event", "explicit", "extern", "false", "finally",
		"fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
		"interface", "internal", "is", "lock", "long", "namespace", "new", "null",
		"object", "operator", "out", "override", "params", "private", "protected",
		"public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof",
		"stackalloc", "static", "string", "struct", "switch", "this", "throw", "true",
		"try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using",
		"virtual", "void", "volatile", "while":
		return true
	default:
		return false
	}
}

func decodeSchema(data []byte) (schemaDocument, error) {
	var schema schemaDocument
	if err := json.Unmarshal(data, &schema); err != nil {
		return nil, err
	}
	return schema, nil
}
